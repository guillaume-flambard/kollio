import { expect, test } from '@playwright/test'

test('Spatial Ink navigates a real hundred-object graph without document mutations', async ({ page }) => {
  await page.goto('/spatial-v3?stress=100')
  const nodes = page.locator('.spatial-v3__node')
  const paths = page.locator('.spatial-v3__edges path')
  await expect(nodes).toHaveCount(100)
  await expect(paths).toHaveCount(200)
  await page.waitForFunction(() => Boolean((document.querySelector('#__nuxt') as HTMLElement & { __vue_app__?: unknown } | null)?.__vue_app__))
  const search = page.getByRole('searchbox')
  await search.fill('Objet 42')
  await page.locator('.spatial-v3__matches button').filter({ hasText: 'Objet 42' }).first().click()
  await expect(page.locator('.spatial-v3__focusbar')).toBeVisible()
  await expect(page.locator('.spatial-v3__trail')).toContainText('Objet 42')
  await expect(page.locator('.spatial-v3__neighbors button').first()).toBeVisible()
  await page.locator('.spatial-v3__neighbors button').first().click()
  await expect(page.locator('.spatial-v3__trail button')).toHaveCount(3)
  await page.locator('.spatial-v3__trail button').nth(1).click()
  await expect(page.locator('.spatial-v3__trail button')).toHaveCount(2)
  await page.getByRole('button', { name: 'Revenir au contexte' }).click()
  await expect(page.locator('.spatial-v3__focusbar')).toHaveCount(0)
  await expect(nodes).toHaveCount(100)
  await expect(paths).toHaveCount(200)
})
